/** Locale bundles for the tools employee card. */

/** The fields that carry a label and a hint. */
export type ToolsFieldKey =
  | 'enabled' | 'weekday' | 'shiftTime' | 'timeZone' | 'notifyTo' | 'seedTopics' | 'markets' | 'maxToolsPerWeek' | 'serpPerDay'
  | 'adsenseClient' | 'gscProperty' | 'googleServiceAccountKey' | 'seoSiteId' | 'siteRepo' | 'deployHook'
  | 'shiftModel' | 'fallbackModelPick' | 'fallbackCooldownMinutes'

type ListKey = 'seedTopics' | 'markets'
type WeekdayKey = 'monday' | 'tuesday' | 'wednesday' | 'thursday' | 'friday' | 'saturday' | 'sunday'
type ActionKey = 'run-now' | 'publish-site' | 'check-site'
type SiteStateKey = 'live' | 'outdated' | 'not-deployed' | 'unreachable' | 'unknown'
type TestsKey = 'passed' | 'failed' | 'unknown'

/** Locale keys the card renders. */
export type ToolsLocaleKey =
  | 'toolsTitle' | 'toolsDescription' | 'toolsInvalid'
  | 'toolsStatusTitle' | 'toolsStatusLoading' | 'toolsStatusUnknown' | 'toolsScheduled' | 'toolsOff' | 'toolsLastRun'
  | 'toolsRunNow' | 'toolsPublishSite' | 'toolsCheckSite' | 'toolsRefresh' | 'toolsRunProgress' | 'toolsRunAbandoned'
  | `toolsRunKind.${'research' | 'build'}` | `toolsActionOk.${ActionKey}` | `toolsRefused.${ActionKey}`
  | 'toolsSiteTitle' | `toolsSiteState.${SiteStateKey}` | 'toolsSiteVersions' | 'toolsSiteChecked' | 'toolsSiteNoVersion'
  | 'toolsPushReady' | 'toolsPushNotReady' | 'toolsPushNoRepo' | 'toolsDeployHookSet' | 'toolsDeployHookUnset'
  | 'toolsShortlistPending' | 'toolsShortlistPendingHint' | 'toolsShortlistReview' | 'toolsShortlistDecided' | 'toolsShortlistOpen'
  | 'toolsShortlistItem' | 'toolsShortlistFacts'
  | 'toolsMark.approved' | 'toolsMark.rejected' | 'toolsMark.undecided' | 'toolsMark.built' | 'toolsMark.published'
  | 'toolsPublishedTitle' | 'toolsNoTools' | 'toolsSeedTag'
  | 'toolsCol.tool' | 'toolsCol.tests' | 'toolsCol.live' | 'toolsCol.search' | 'toolsCol.flag'
  | `toolsTests.${TestsKey}` | 'toolsLive.yes' | 'toolsLive.no' | 'toolsGsc.clicks' | 'toolsGsc.impressions' | 'toolsGsc.position'
  | 'toolsAdsenseTitle' | 'toolsAdsenseReady' | 'toolsAdsenseNotReady' | 'toolsAdsenseClientSet' | 'toolsAdsenseClientUnset'
  | 'toolsGscConnected' | 'toolsGscLastReview' | 'toolsGscNotConnected' | 'toolsKpAvailable' | 'toolsKpUnavailable'
  | 'toolsPace' | 'toolsSerp' | 'toolsRemove'
  | `toolsWeekday.${WeekdayKey}` | `toolsAdd.${ListKey}` | `tools.${ListKey}.placeholder`
